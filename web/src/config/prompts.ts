import type { Role } from "@/types";

/**
 * 各端预置提示词。
 *
 * 写法遵循优秀教育提示词的通用公式（角色定位 + 数据锚点 + 任务分层 + 硬约束 + 输出格式）：
 * 1. **角色**：开头就告诉模型"你此刻是谁"（学业教练 / 命题助手 / 复盘助手…），
 *    让它按对应的专业口吻作答；
 * 2. **数据锚点**：只引用本系统真实拥有的数据（风险分六因素、考勤、作业正确率、
 *    错题记录、资源库…），不出现需要用户额外补充的占位符，点「添加」就能发；
 * 3. **任务分层**：复杂任务拆成编号步骤，模型按序执行不遗漏；
 * 4. **硬约束**：字数、题量、难度标注、语气红线写得越死，产出越稳；
 * 5. **输出格式**：规定表格 / 分档 / 固定四段等结构，答案拿来就能用。
 */
export interface PromptItem {
  /** 标签名，如「精准出题」；展示与插入输入框时都带【】 */
  tag: string;
  /** 列表里的一句话说明 */
  desc: string;
  /** 发送时携带的完整提示词（含【标签】头） */
  text: string;
}

